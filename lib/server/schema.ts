/** Idempotent schema, applied on the first query of each server instance. */
export const SCHEMA = [
  `CREATE TABLE IF NOT EXISTS profiles (
    user_id           text PRIMARY KEY,
    sex               text CHECK (sex IN ('m', 'f')),
    birth_year        int CHECK (birth_year BETWEEN 1900 AND 2100),
    height_cm         numeric CHECK (height_cm > 0),
    weight_kg         numeric CHECK (weight_kg > 0),
    base_kcal         int CHECK (base_kcal > 0),
    goal_delta        int NOT NULL DEFAULT 0,
    eat_back          numeric NOT NULL DEFAULT 0.75,
    protein_per_kg    numeric NOT NULL DEFAULT 1.8,
    fat_pct           numeric NOT NULL DEFAULT 0.27,
    tz                text NOT NULL DEFAULT 'Europe/Madrid',
    onboarded         boolean NOT NULL DEFAULT false,
    step_token_hash   text UNIQUE,
    hevy_key          text,
    strava_athlete_id bigint,
    strava_name       text,
    strava_access     text,
    strava_refresh    text,
    strava_expires_at bigint,
    synced_at         timestamptz,
    updated_at        timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS entries (
    id         text PRIMARY KEY,
    user_id    text NOT NULL,
    date       date NOT NULL,
    meal       text NOT NULL CHECK (meal IN ('desayuno', 'comida', 'merienda', 'cena', 'snacks')),
    food_id    text,
    name       text NOT NULL,
    brand      text,
    grams      numeric NOT NULL CHECK (grams > 0),
    kcal       numeric NOT NULL CHECK (kcal >= 0),
    protein    numeric NOT NULL CHECK (protein >= 0),
    carbs      numeric NOT NULL CHECK (carbs >= 0),
    fat        numeric NOT NULL CHECK (fat >= 0),
    image      text,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX IF NOT EXISTS entries_user_date ON entries (user_id, date)`,
  `CREATE TABLE IF NOT EXISTS workouts (
    id          text PRIMARY KEY,
    user_id     text NOT NULL,
    date        date NOT NULL,
    type        text NOT NULL,
    title       text,
    minutes     numeric NOT NULL CHECK (minutes > 0),
    intensity   text NOT NULL,
    distance_km numeric,
    kcal        int NOT NULL CHECK (kcal >= 0),
    kcal_source text NOT NULL,
    source      text NOT NULL,
    external_id text,
    start_at    timestamptz,
    details     jsonb,
    hidden      boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, source, external_id)
  )`,
  `CREATE INDEX IF NOT EXISTS workouts_user_date ON workouts (user_id, date)`,
  `CREATE TABLE IF NOT EXISTS steps (
    user_id    text NOT NULL,
    date       date NOT NULL,
    steps      int NOT NULL CHECK (steps >= 0),
    source     text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, date)
  )`,
  `CREATE TABLE IF NOT EXISTS weights (
    user_id text NOT NULL,
    date    date NOT NULL,
    kg      numeric NOT NULL CHECK (kg > 0),
    PRIMARY KEY (user_id, date)
  )`,
  `CREATE TABLE IF NOT EXISTS foods (
    id         text PRIMARY KEY,
    owner      text,
    data       jsonb NOT NULL,
    fetched_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX IF NOT EXISTS foods_owner ON foods (owner)`,
];
